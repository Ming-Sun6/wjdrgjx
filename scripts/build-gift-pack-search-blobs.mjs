import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const REGULAR_HTML = path.join(ROOT, "public", "function", "Zero", "regular-gift-data.html");
const SPECIAL_HTML = path.join(ROOT, "public", "function", "Zero", "special-gift-data.html");
const OUTPUT_JS = path.join(ROOT, "public", "function", "Zero", "gift-pack-search-blobs.js");

function extractPacksArray(html) {
  const needle = "const packs";
  const i = html.indexOf(needle);
  if (i < 0) throw new Error(`missing ${needle}`);
  const j = html.indexOf("=", i);
  const start = html.indexOf("[", j);
  let depth = 0;
  for (let k = start; k < html.length; k++) {
    const c = html[k];
    if (c === "[") depth++;
    else if (c === "]") {
      depth--;
      if (depth === 0) {
        return JSON.parse(html.slice(start, k + 1));
      }
    }
  }
  throw new Error("unclosed [ for packs array");
}

function normalizeText(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[\s·•\-_.，。、；;：:（）()【】\[\]《》<>]/g, "");
}

function textOfPack(pack) {
  const base = [pack.name || "", pack.note || ""];
  for (const s of pack.sections || []) {
    base.push(s.title || "");
    for (const c of s.columns || []) base.push(c);
  }
  return normalizeText(base.join(" "));
}

function main() {
  const blobs = {};
  for (const [key, filePath] of [
    ["regular", REGULAR_HTML],
    ["special", SPECIAL_HTML],
  ]) {
    const html = fs.readFileSync(filePath, "utf8");
    const packs = extractPacksArray(html);
    blobs[key] = packs.map((p) => ({ n: p.name || "", t: textOfPack(p) }));
  }
  const header =
    "// AUTO-GENERATED by scripts/build-gift-pack-search-blobs.mjs — do not edit by hand.\n";
  const body = `(function(){window.__giftPackSearchBlobs=${JSON.stringify(blobs)};})();\n`;
  fs.writeFileSync(OUTPUT_JS, header + body, "utf8");
  console.log(
    `wrote ${OUTPUT_JS} regular:${blobs.regular.length} special:${blobs.special.length}`,
  );
}

main();
