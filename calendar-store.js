const ULID_ALPHABET = '0123456789abcdefghjkmnpqrstvwxyz';

function createCustomCategoryCode(random, now) {
  const rng = typeof random === 'function' ? random : Math.random;
  let time = Number(typeof now === 'function' ? now() : Date.now());
  let encodedTime = '';
  for (let index = 0; index < 10; index += 1) {
    encodedTime = ULID_ALPHABET[time % 32] + encodedTime;
    time = Math.floor(time / 32);
  }
  let entropy = '';
  for (let index = 0; index < 16; index += 1) entropy += ULID_ALPHABET[Math.floor(rng() * 32) % 32];
  return `custom-${encodedTime}${entropy}`;
}

function jsonParse(value, fallback) {
  if (Array.isArray(value) || value && typeof value === 'object') return value;
  try { return JSON.parse(value); } catch (_error) { return fallback; }
}

function bool(value) {
  return value === true || value === 1 || value === '1';
}

function mapLegacyGroup(rows) {
  const list = (Array.isArray(rows) ? rows : []).slice().sort((a, b) => String(a.date).localeCompare(String(b.date)));
  const dates = Array.from(new Set(list.map((row) => String(row.date))));
  let scheduleType = dates.length === 1 ? 'single' : 'continuous';
  for (let index = 1; index < dates.length; index += 1) {
    if (dates[index] !== addDays(dates[index - 1], 1)) scheduleType = 'date-list';
  }
  const first = list[0] || {};
  return {
    legacyOriginalId: first.original_id || first.originalId || null,
    name: first.name || '未命名日程',
    scheduleType,
    startDate: dates[0],
    endDate: dates[dates.length - 1],
    legacyDates: scheduleType === 'date-list' ? dates : null,
    startTime: first.start_time || first.startTime || '',
    endTime: first.end_time || first.endTime || '',
    color: first.color || null,
    description: first.description || '',
    createdBy: first.created_by || first.createdBy || null
  };
}

async function seedCategories(adapter) {
  for (const category of PRESET_CATEGORIES) {
    if (adapter.pgDatabase) {
      await adapter.execute(
        `INSERT INTO calendar_categories (code,name,color,sort_order,enabled,updated_at)
         VALUES (?,?,?,?,true,CURRENT_TIMESTAMP(3)) ON CONFLICT (code) DO NOTHING`,
        [category.code, category.name, category.color, category.sortOrder]
      );
    } else {
      await adapter.execute(
        `INSERT IGNORE INTO calendar_categories (code,name,color,sort_order,enabled,updated_at)
         VALUES (?,?,?,?,1,CURRENT_TIMESTAMP(3))`,
        [category.code, category.name, category.color, category.sortOrder]
      );
    }
  }
}

async function migrateLegacyCalendarSchedules(adapter) {
  const regular = await adapter.queryOne('SELECT id,code FROM calendar_categories WHERE code = ? LIMIT 1', ['regular']);
  if (!regular) throw new Error('REGULAR_CATEGORY_MISSING');
  let rows = [];
  try {
    rows = await adapter.queryRows(
      `SELECT original_id,name,date,start_time,end_time,color,description,created_by
       FROM calendar_schedules ORDER BY original_id,date,id`
    );
  } catch (error) {
    if (/does not exist|doesn't exist|no such table/i.test(String(error && error.message || error))) return;
    throw error;
  }
  const groups = new Map();
  for (const row of rows) {
    const key = String(row.original_id || '');
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(row);
  }
  for (const [legacyId, groupRows] of groups) {
    if (!legacyId) continue;
    const exists = await adapter.queryOne('SELECT id FROM calendar_schedule_definitions WHERE legacy_original_id = ? LIMIT 1', [legacyId]);
    if (exists) continue;
    const value = mapLegacyGroup(groupRows);
    await adapter.runInTransaction(async (tx) => {
      await tx.execute(
        `INSERT INTO calendar_schedule_definitions
         (legacy_original_id,category_id,name,schedule_type,composite_layout,start_date,end_date,legacy_dates_json,start_time,end_time,color,description,enabled,created_by,updated_at)
         VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?, ?,CURRENT_TIMESTAMP(3))`,
        [legacyId, Number(regular.id), value.name, value.scheduleType, null, value.startDate, value.endDate,
          value.legacyDates ? JSON.stringify(value.legacyDates) : null, value.startTime || null, value.endTime || null,
          value.color, value.description || null, adapter.pgDatabase ? true : 1, value.createdBy]
      );
    });
  }
}

async function ensureCalendarSchema(adapter) {
  for (const sql of adapter.pgDatabase ? CALENDAR_DDL_PG : CALENDAR_DDL_MYSQL) await adapter.execute(sql);
  for (const column of [
    `sort_order ${adapter.pgDatabase ? 'integer' : 'INT'} NOT NULL DEFAULT 0`,
    `font_bold ${adapter.pgDatabase ? 'boolean' : 'TINYINT(1)'} NOT NULL DEFAULT ${adapter.pgDatabase ? 'false' : '0'}`
  ]) {
    try {
      await adapter.execute(`ALTER TABLE calendar_schedule_definitions ADD COLUMN ${column}`);
    } catch (error) {
      if (!/duplicate|already exists|column .* exists/i.test(String(error && error.message || error))) throw error;
    }
  }
  await seedCategories(adapter);
  await migrateLegacyCalendarSchedules(adapter);
}

