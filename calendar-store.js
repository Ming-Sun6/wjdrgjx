function createCalendarStore(adapter) {
  async function listCategories() {
    const rows = await adapter.queryRows('SELECT id,code,name,color,sort_order,enabled FROM calendar_categories ORDER BY sort_order,name,id');
    return rows.map(mapCategoryRow);
  }

  async function getCategoryById(id) {
    const row = await adapter.queryOne('SELECT id,code,name,color,sort_order,enabled FROM calendar_categories WHERE id = ? LIMIT 1', [id]);
    return row ? mapCategoryRow(row) : null;
  }

  async function listDefinitions(includeDisabled) {
    const enabledValue = adapter.pgDatabase ? 'true' : '1';
    const where = includeDisabled ? '' : `WHERE d.enabled = ${enabledValue} AND c.enabled = ${enabledValue}`;
    const rows = await adapter.queryRows(
      `SELECT d.*,c.code AS category_code,c.name AS category_name,c.color AS category_color,c.sort_order AS category_sort_order,c.enabled AS category_enabled
       FROM calendar_schedule_definitions d JOIN calendar_categories c ON c.id=d.category_id ${where}
       ORDER BY c.sort_order,d.sort_order,d.start_date,d.id`
    );
    const ids = rows.map((row) => Number(row.id));
    const itemRows = ids.length ? await adapter.queryRows(`SELECT * FROM calendar_schedule_items WHERE schedule_id IN (${ids.map(() => '?').join(',')}) ORDER BY schedule_id,sort_order,id`, ids) : [];
    const exceptionRows = ids.length ? await adapter.queryRows(`SELECT * FROM calendar_schedule_exceptions WHERE schedule_id IN (${ids.map(() => '?').join(',')}) ORDER BY schedule_id,occurrence_date,id`, ids) : [];
    const itemMap = new Map();
    for (const row of itemRows) {
      const key = Number(row.schedule_id);
      if (!itemMap.has(key)) itemMap.set(key, []);
      itemMap.get(key).push(mapItemRow(row));
    }
    const exceptionMap = new Map();
    for (const row of exceptionRows) {
      const key = Number(row.schedule_id);
      if (!exceptionMap.has(key)) exceptionMap.set(key, []);
      exceptionMap.get(key).push({ id: Number(row.id), scheduleId: key, occurrenceDate: row.occurrence_date, scope: row.scope, name: row.name, color: row.color || null, fontBold: bool(row.font_bold), enabled: bool(row.enabled) });
    }
    return rows.map((row) => {
      const definition = mapDefinitionRow(row, mapCategoryRow({
      id: row.category_id,
      code: row.category_code,
      name: row.category_name,
      color: row.category_color,
      sort_order: row.category_sort_order,
      enabled: row.category_enabled
      }), itemMap.get(Number(row.id)) || []);
      definition.exceptions = exceptionMap.get(Number(row.id)) || [];
      return definition;
    });
  }

  async function createCategory(input, meta) {
    const existing = await adapter.queryOne('SELECT id FROM calendar_categories WHERE name = ? LIMIT 1', [input.name]);
    if (existing) return { error: 'CATEGORY_NAME_EXISTS' };
    for (let attempt = 0; attempt < 5; attempt += 1) {
      const code = createCustomCategoryCode(meta && meta.random, meta && meta.now);
      try {
        const params = [code, input.name, input.color, Number(input.sortOrder || 0)];
        const result = adapter.pgDatabase
          ? await adapter.queryOne('INSERT INTO calendar_categories (code,name,color,sort_order,enabled,updated_at) VALUES (?,?,?,?,true,CURRENT_TIMESTAMP(3)) RETURNING id', params)
          : await adapter.execute('INSERT INTO calendar_categories (code,name,color,sort_order,enabled,updated_at) VALUES (?,?,?,?,1,CURRENT_TIMESTAMP(3))', params);
        return getCategoryById(Number(result.id || result.insertId));
      } catch (error) {
        const message = String(error && (error.code || error.message) || error);
        if (/name|category.*name/i.test(message)) return { error: 'CATEGORY_NAME_EXISTS' };
        if (!/duplicate|unique|23505|ER_DUP_ENTRY/i.test(message)) throw error;
      }
    }
    return { error: 'CATEGORY_CODE_GENERATION_FAILED' };
  }

  async function getCategoryByCode(code) {
    const row = await adapter.queryOne('SELECT id,code,name,color,sort_order,enabled FROM calendar_categories WHERE code = ? LIMIT 1', [code]);
    return row ? mapCategoryRow(row) : null;
  }

  async function updateCategory(id, input) {
    const duplicate = await adapter.queryOne('SELECT id FROM calendar_categories WHERE name = ? AND id <> ? LIMIT 1', [input.name, id]);
    if (duplicate) return { error: 'CATEGORY_NAME_EXISTS' };
    const result = await adapter.execute('UPDATE calendar_categories SET name=?,color=?,updated_at=CURRENT_TIMESTAMP(3) WHERE id=?', [input.name, input.color, id]);
    if (!Number(result.affectedRows === undefined ? 1 : result.affectedRows)) return null;
    return getCategoryById(id);
  }

  async function reorderCategories(ids) {
    const categories = await listCategories();
    if (ids.length !== categories.length || new Set(ids).size !== ids.length || categories.some((category) => !ids.includes(category.id))) return { error: 'BAD_CATEGORY_ORDER' };
    await adapter.runInTransaction(async (tx) => {
      for (let index = 0; index < ids.length; index += 1) {
        await tx.execute('UPDATE calendar_categories SET sort_order=?,updated_at=CURRENT_TIMESTAMP(3) WHERE id=?', [(index + 1) * 10, ids[index]]);
      }
    });
    return listCategories();
  }

  async function setCategoryStatus(id, enabled) {
    const result = await adapter.execute('UPDATE calendar_categories SET enabled=?,updated_at=CURRENT_TIMESTAMP(3) WHERE id=?', [adapter.pgDatabase ? !!enabled : enabled ? 1 : 0, id]);
    if (!Number(result.affectedRows === undefined ? 1 : result.affectedRows)) return null;
    return getCategoryById(id);
  }

  function definitionParams(value, actorId) {
    const recurrence = value.recurrence || {};
    return [
      value.legacyOriginalId || null,
      value.categoryId,
      value.name,
      value.scheduleType,
      value.compositeLayout || null,
      value.startDate,
      value.endDate,
      value.legacyDates && value.legacyDates.length ? JSON.stringify(value.legacyDates) : null,
      value.startTime || null,
      value.endTime || null,
      value.color || null,
      value.description || null,
      Number(value.sortOrder || 0),
      adapter.pgDatabase ? value.fontBold === true : value.fontBold === true ? 1 : 0,
      adapter.pgDatabase ? value.enabled !== false : value.enabled === false ? 0 : 1,
      value.recurrenceUnit || recurrence.unit || null,
      value.recurrenceInterval || recurrence.interval || null,
      value.weekdays && value.weekdays.length ? JSON.stringify(value.weekdays) : recurrence.weekdays && recurrence.weekdays.length ? JSON.stringify(recurrence.weekdays) : null,
      value.monthDay || recurrence.monthDay || null,
      value.recurrenceEndType || recurrence.endType || null,
      value.recurrenceUntil || recurrence.until || null,
      value.recurrenceCount || recurrence.count || null,
      actorId || null
    ];
  }

  function itemParams(scheduleId, item) {
    const recurrence = item.recurrence || {};
    return [
      scheduleId,
      item.name,
      item.description || null,
      item.color || null,
      Number(item.sortOrder || 0),
      adapter.pgDatabase ? item.highlighted === true : item.highlighted === true ? 1 : 0,
      adapter.pgDatabase ? item.enabled !== false : item.enabled === false ? 0 : 1,
      item.dateMode,
      item.startOffsetDays === undefined ? null : item.startOffsetDays,
      item.endOffsetDays === undefined ? null : item.endOffsetDays,
      item.selectedOffsets && item.selectedOffsets.length ? JSON.stringify(item.selectedOffsets) : null,
      item.durationDays || null,
      item.startTime || null,
      item.endTime || null,
      item.recurrenceUnit || recurrence.unit || null,
      item.recurrenceInterval || recurrence.interval || null,
      item.weekdays && item.weekdays.length ? JSON.stringify(item.weekdays) : recurrence.weekdays && recurrence.weekdays.length ? JSON.stringify(recurrence.weekdays) : null,
      item.monthDay || recurrence.monthDay || null,
      item.recurrenceEndType || recurrence.endType || null,
      item.recurrenceUntilOffset === undefined || item.recurrenceUntilOffset === null ? recurrence.untilOffset === undefined ? null : recurrence.untilOffset : item.recurrenceUntilOffset,
      item.recurrenceCount || recurrence.count || null
    ];
  }

  async function insertAndGetId(tx, sql, params) {
    if (adapter.pgDatabase) {
      const row = await tx.queryOne(`${sql} RETURNING id`, params);
      return Number(row.id);
    }
    const result = await tx.execute(sql, params);
    return Number(result.insertId);
  }

  async function insertItem(tx, scheduleId, item) {
    return insertAndGetId(tx,
      `INSERT INTO calendar_schedule_items
       (schedule_id,name,description,color,sort_order,highlighted,enabled,date_mode,start_offset_days,end_offset_days,selected_offsets_json,duration_days,start_time,end_time,recurrence_unit,recurrence_interval,weekdays_json,month_day,recurrence_end_type,recurrence_until_offset,recurrence_count,updated_at)
       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,CURRENT_TIMESTAMP(3))`,
      itemParams(scheduleId, item));
  }

  async function createDefinition(value, meta) {
    const id = await adapter.runInTransaction(async (tx) => {
      const definitionId = await insertAndGetId(tx,
        `INSERT INTO calendar_schedule_definitions
         (legacy_original_id,category_id,name,schedule_type,composite_layout,start_date,end_date,legacy_dates_json,start_time,end_time,color,description,sort_order,font_bold,enabled,recurrence_unit,recurrence_interval,weekdays_json,month_day,recurrence_end_type,recurrence_until,recurrence_count,created_by,updated_at)
         VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,CURRENT_TIMESTAMP(3))`,
        definitionParams(value, meta && meta.actorId));
      for (const item of value.items || []) await insertItem(tx, definitionId, item);
      return definitionId;
    });
    return getDefinition(id);
  }

  async function getDefinition(id) {
    const definitions = await listDefinitions(true);
    return definitions.find((definition) => definition.id === Number(id)) || null;
  }

  async function getDefinitionByLegacyId(legacyId) {
    const castType = adapter.pgDatabase ? 'TEXT' : 'CHAR';
    const row = await adapter.queryOne(`SELECT id FROM calendar_schedule_definitions WHERE legacy_original_id = ? OR CAST(id AS ${castType}) = ? LIMIT 1`, [legacyId, legacyId]);
    return row ? getDefinition(Number(row.id)) : null;
  }

  async function replaceDefinition(id, value, meta) {
    const current = await getDefinition(id);
    if (!current) return null;
    const existingIds = new Set((current.items || []).map((item) => item.id));
    for (const item of value.items || []) {
      if (item.id && !existingIds.has(Number(item.id))) return { error: 'BAD_ITEM_ID' };
    }
    await adapter.runInTransaction(async (tx) => {
      if (meta && meta.clearExceptions) await tx.execute('DELETE FROM calendar_schedule_exceptions WHERE schedule_id=?', [id]);
      const params = definitionParams({ ...value, legacyOriginalId: value.legacyOriginalId || current.legacyOriginalId }, meta && meta.actorId);
      await tx.execute(
        `UPDATE calendar_schedule_definitions SET
         legacy_original_id=?,category_id=?,name=?,schedule_type=?,composite_layout=?,start_date=?,end_date=?,legacy_dates_json=?,start_time=?,end_time=?,color=?,description=?,sort_order=?,font_bold=?,enabled=?,recurrence_unit=?,recurrence_interval=?,weekdays_json=?,month_day=?,recurrence_end_type=?,recurrence_until=?,recurrence_count=?,created_by=?,updated_at=CURRENT_TIMESTAMP(3)
         WHERE id=?`,
        [...params, id]);
      const submittedIds = new Set();
      for (const item of value.items || []) {
        if (item.id) {
          submittedIds.add(Number(item.id));
          await tx.execute(
            `UPDATE calendar_schedule_items SET name=?,description=?,color=?,sort_order=?,highlighted=?,enabled=?,date_mode=?,start_offset_days=?,end_offset_days=?,selected_offsets_json=?,duration_days=?,start_time=?,end_time=?,recurrence_unit=?,recurrence_interval=?,weekdays_json=?,month_day=?,recurrence_end_type=?,recurrence_until_offset=?,recurrence_count=?,updated_at=CURRENT_TIMESTAMP(3) WHERE id=? AND schedule_id=?`,
            [...itemParams(id, item).slice(1), Number(item.id), id]);
        } else {
          await insertItem(tx, id, item);
        }
      }
      const removed = [...existingIds].filter((itemId) => !submittedIds.has(itemId));
      if (removed.length) await tx.execute(`DELETE FROM calendar_schedule_items WHERE schedule_id=? AND id IN (${removed.map(() => '?').join(',')})`, [id, ...removed]);
    });
    return getDefinition(id);
  }

  async function copyDefinition(id, meta) {
    const current = await getDefinition(id);
    if (!current) return null;
    return createDefinition({
      ...current,
      id: undefined,
      legacyOriginalId: null,
      name: `${current.name}副本`,
      enabled: false,
      items: current.items.map((item) => ({ ...item, id: null }))
    }, meta);
  }

  async function setDefinitionStatus(id, enabled) {
    const result = await adapter.execute('UPDATE calendar_schedule_definitions SET enabled=?,updated_at=CURRENT_TIMESTAMP(3) WHERE id=?', [adapter.pgDatabase ? !!enabled : enabled ? 1 : 0, id]);
    if (!Number(result.affectedRows === undefined ? 1 : result.affectedRows)) return null;
    return getDefinition(id);
  }

  async function reorderDefinitions(items) {
    const list = Array.isArray(items) ? items.map((item) => ({ id: Number(item.id), sortOrder: Number(item.sortOrder) })) : [];
    if (!list.length || list.some((item) => !Number.isInteger(item.id) || !Number.isInteger(item.sortOrder)) || new Set(list.map((item) => item.id)).size !== list.length) return { error: 'BAD_SCHEDULE_ORDER' };
    const known = new Set((await listDefinitions(true)).map((item) => item.id));
    if (list.some((item) => !known.has(item.id))) return { error: 'BAD_SCHEDULE_ORDER' };
    await adapter.runInTransaction(async (tx) => {
      for (const item of list) await tx.execute('UPDATE calendar_schedule_definitions SET sort_order=?,updated_at=CURRENT_TIMESTAMP(3) WHERE id=?', [item.sortOrder, item.id]);
    });
    return listDefinitions(true);
  }

  async function upsertOccurrenceException(scheduleId, occurrenceDate, scope, values) {
    const params = [scheduleId, occurrenceDate, scope, values.name, values.color || null, adapter.pgDatabase ? values.fontBold === true : values.fontBold === true ? 1 : 0, adapter.pgDatabase ? values.enabled !== false : values.enabled === false ? 0 : 1];
    if (adapter.pgDatabase) {
      await adapter.execute(`INSERT INTO calendar_schedule_exceptions (schedule_id,occurrence_date,scope,name,color,font_bold,enabled,updated_at) VALUES (?,?,?,?,?,?,?,CURRENT_TIMESTAMP(3)) ON CONFLICT (schedule_id,occurrence_date,scope) DO UPDATE SET name=EXCLUDED.name,color=EXCLUDED.color,font_bold=EXCLUDED.font_bold,enabled=EXCLUDED.enabled,updated_at=CURRENT_TIMESTAMP(3)`, params);
    } else {
      await adapter.execute(`INSERT INTO calendar_schedule_exceptions (schedule_id,occurrence_date,scope,name,color,font_bold,enabled,updated_at) VALUES (?,?,?,?,?,?,?,CURRENT_TIMESTAMP(3)) ON DUPLICATE KEY UPDATE name=VALUES(name),color=VALUES(color),font_bold=VALUES(font_bold),enabled=VALUES(enabled),updated_at=CURRENT_TIMESTAMP(3)`, params);
    }
    return getDefinition(scheduleId);
  }

  async function deleteDefinition(id) {
    return adapter.runInTransaction(async (tx) => {
      await tx.execute('DELETE FROM calendar_schedule_items WHERE schedule_id=?', [id]);
      await tx.execute('DELETE FROM calendar_schedule_exceptions WHERE schedule_id=?', [id]);
      const result = await tx.execute('DELETE FROM calendar_schedule_definitions WHERE id=?', [id]);
      return Number(result.affectedRows === undefined ? 1 : result.affectedRows) > 0;
    });
  }

  return {
    listCategories,
    getCategoryById,
    getCategoryByCode,
    createCategory,
    updateCategory,
    reorderCategories,
    setCategoryStatus,
    listDefinitions,
    getDefinition,
    getDefinitionByLegacyId,
    createDefinition,
    replaceDefinition,
    copyDefinition,
    setDefinitionStatus,
    reorderDefinitions,
    upsertOccurrenceException,
    deleteDefinition
  };
}

